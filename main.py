def send_post(text):
    if not BOT_TOKEN or not CHANNEL_ID:
        print("Ошибка: BOT_TOKEN или CHANNEL_ID не задан")
        return

    url = f"https://api.telegram.org/bot{BOT_TOKEN}/sendMessage"

    try:
        response = requests.post(
            url,
            json={
                "chat_id": CHANNEL_ID,
                "text": text
            },
            timeout=30
        )

        print("Telegram:", response.status_code, response.text)

    except Exception as e:
        print("Ошибка отправки:", e)


# Счётчик постов
post_number = 0


def scheduled_post():
    global post_number

    text = POSTS[post_number % len(POSTS)]
    send_post(text)

    post_number += 1


# Планировщик
scheduler = BackgroundScheduler(timezone="Europe/Moscow")

scheduler.add_job(
    scheduled_post,
    CronTrigger(
        hour="9-23",
        minute=0,
        timezone="Europe/Moscow"
    ),
    id="telegram_posts",
    replace_existing=True
)

scheduler.start()


